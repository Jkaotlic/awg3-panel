package wgconf

import "strings"

// PeerNameMaxLen — потолок длины имени, подхватываемого из комментария.
// Значение продиктовано не этим пакетом, а issuer.validateName: имя длиннее
// сорока символов панель отказывается принимать при правке. Константа
// продублирована, а не импортирована, потому что issuer сам импортирует
// wgconf — обратная зависимость была бы циклом. Расходиться им нельзя:
// подхваченное имя обязано быть таким, какое панель примет обратно.
const PeerNameMaxLen = 40

// peerNameAuthorPrefix — пометка авторства, которую RenderPeerBlock ставит
// перед именем выпущенного панелью пира. Частью имени она не является и
// снимается при чтении: иначе один и тот же пир назывался бы по-разному до
// и после того, как его подхватит Reconcile.
const peerNameAuthorPrefix = "awg3panel:"

// PeerName возвращает имя пира, записанное комментарием ВНУТРИ блока [Peer],
// либо "" — если комментария нет или он именем быть не может.
//
// Зачем это нужно. Разбор конфига комментарии отбрасывает (см. Parse), а
// имена пиров, заведённых руками до установки панели, существуют ТОЛЬКО в
// них: в peers.json такого пира нет вовсе, пока State.Reconcile его не
// подхватит. Без этой функции подхваченный пир получает имя "peer-<12 hex>",
// которое человек не выбирал; а поскольку удаление в консоли подтверждается
// вводом имени символ в символ, такие пиры оказываются практически
// неудаляемыми — что и случилось на боевом awg3, где так назывались пять
// пиров из шести.
//
// Читается ПЕРВЫЙ комментарий блока: RenderPeerBlock ставит имя сразу после
// заголовка, и та же привычка у конфигов, писанных руками. Комментарии
// ниже — пояснения («добавлен вручную», дата), и брать их за имя неверно.
//
// Отвергается то, что панель не примет обратно как имя: пустое, длиннее
// PeerNameMaxLen, со скобками заголовка секции (PeerSpec.validate). Отказ
// молчаливый и означает «имени нет» — вызывающий подставит своё запасное.
func PeerName(sec *Section, raw string) string {
	if sec == nil {
		return ""
	}
	for _, line := range strings.Split(sec.Bytes(raw), "\n") {
		t := strings.TrimSpace(strings.TrimSuffix(line, "\r"))
		if t == "" || strings.HasPrefix(t, "[") {
			continue // заголовок секции и пустые строки — не комментарии
		}
		if !strings.HasPrefix(t, "#") && !strings.HasPrefix(t, ";") {
			return "" // дошли до первого параметра — комментария перед ним не было
		}
		name := strings.TrimSpace(t[1:])
		after, byPanel := strings.CutPrefix(name, peerNameAuthorPrefix)
		if byPanel {
			name = strings.TrimSpace(after)
		} else {
			name = headOf(name)
		}
		if name == "" || len([]rune(name)) > PeerNameMaxLen || strings.ContainsAny(name, "[]") {
			return ""
		}
		return name
	}
	return ""
}

// nameSeparators — разделители «название — пояснение» в комментариях,
// писанных руками. С пробелами по краям намеренно: голый дефис разрезал бы
// «office-vpn» по собственному имени.
var nameSeparators = []string{" — ", " – ", " - "}

// headOf возвращает голову комментария до первого разделителя, но ТОЛЬКО
// если сам комментарий в потолок не влезает. Комментарий, который влезает,
// возвращается целиком: «me — Keenetic (дом)» информативнее, чем «me».
//
// Правило выведено из привычки боевых конфигов, а не придумано: комментарии
// там устроены как «<название> — <пояснение, иногда с датой>», и
// отвергнуть такой целиком значит оставить пиру имя «peer-<12 hex>» — то
// самое, которое невозможно осмысленно ввести при подтверждении удаления.
// К комментарию с пометкой авторства панели правило не применяется: там
// после префикса стоит имя, выбранное человеком в консоли, и резать его по
// тире было бы порчей чужого выбора.
func headOf(comment string) string {
	if len([]rune(comment)) <= PeerNameMaxLen {
		return comment
	}
	for _, sep := range nameSeparators {
		if head, _, found := strings.Cut(comment, sep); found {
			return strings.TrimSpace(head)
		}
	}
	return comment
}
