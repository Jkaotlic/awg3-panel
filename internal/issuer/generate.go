// maxRandomTagLen — потолок значения N в одном теге `<r N>` (и в однотипных
// с ним `<rc N>`/`<rd N>`, здесь не используемых), который мы САМИ себе
// назначаем ради переносимости между реализациями, а не потому, что этого
// требует протокол.
//
// Проверено по эталонной реализации amneziawg-go (тег v3.1.20260814,
// device/obf.go, device/obf_rand.go): её сборщик randObf берёт длину из
// строки тега и никак её не ограничивает — `<r 1177>` эталон разбирает без
// возражений, предела в протоколе нет. Независимая реализация на Rust
// (AYastrebov/awgtun) такой предел вводит сама (её разборщик CPS отвергает
// N > AWG2_MAX_CPS_RANDOM_LEN = 1000 при разборе конфига) — это выбор её
// автора, не требование спецификации. Держаться в пределах 1000 не стоит нам
// ничего (на проводе получаются ровно те же случайные байты, только через
// несколько тегов подряд вместо одного), а конфиг с одним огромным тегом
// сторонние реализации с таким ограничением (в том числе Android-обвязка на
// основе awgtun) молча не примут. Отдельно: в самом amneziawg-go есть
// неслитая ветка feature/add-size-limitation с одним коммитом "fix: add i,j
// params size limitation" — похоже, ограничение планируют ввести и в эталон,
// но в релизе его пока нет; если оно доедет до релиза, наши конфиги переживут
// это без правок именно потому, что уже держатся в его пределах.
const maxRandomTagLen = 1000

// randTags разбивает N случайных байт на теги `<r K>`, каждый из которых не
// превышает maxRandomTagLen: несколько тегов подряд на проводе дают ровно
// такую же случайную последовательность байт, что и один большой тег
// (amneziawg-go подставляет случайные байты на каждый тег независимо) — это
// вопрос переносимости между реализациями (см. maxRandomTagLen), а не
// протокольное требование. Нужна только QUIC-профилю (там полезная нагрузка
// перевешивает 1000 байт), но сделана общей на случай, если будущий профиль
// вырастет настолько же.
func randTags(n int) string {
	var sb strings.Builder
	for n > 0 {
		chunk := n
		if chunk > maxRandomTagLen {
			chunk = maxRandomTagLen
		}
		sb.WriteString("<r ")
		sb.WriteString(strconv.Itoa(chunk))
		sb.WriteString(">")
		n -= chunk
	}
	return sb.String()
}

// GenerateSignatureFor — единственная точка входа для сборки поля I1: по
// профилю выбирает один из трёх сборщиков ниже (спека 2026-08-25, разделы
// 5.2-5.4). Профиль, не входящий в profilePort, сюда попасть не должен —
// ValidProfile отсекает его раньше на границе HTTP, — но ошибка здесь
// возвращается честно, а не подставляет DNS по умолчанию: молчаливая
// подстановка замаскировала бы опечатку в коде, вызывающем эту функцию
// напрямую, мимо ValidProfile.
func GenerateSignatureFor(rnd io.Reader, p MimicryProfile) (string, error) {
	switch p {
	case MimicryQUIC:
		return generateQUICSignature(rnd)
	case MimicryDNS:
		return generateDNSSignature(rnd)
	case MimicrySTUN:
		return generateSTUNSignature(rnd)
	default:
		return "", fmt.Errorf("%w: неизвестный профиль мимикрии %q", ErrInvalidInput, p)
	}
}

// generateQUICSignature собирает клиентский Initial-пакет QUIC версии 1
// (спека 2026-08-25, раздел 5.3; структура — RFC 9000 §17.2.2).
//
// Обязательные свойства:
//   - датаграмма не короче 1200 байт: RFC 9000 §14.1 требует от клиента
//     дополнять UDP-датаграмму с Initial до 1200 байт кадрами PADDING —
//     защита от атак с усилением (amplification attack). Пакет короче —
//     аномалия сам по себе, а не деталь, на которой можно сэкономить;
//   - идентификаторы соединения (DCID/SCID) и полезная нагрузка случайны В
//     КАЖДОМ ПАКЕТЕ — через `<r N>`, то есть настоящий amneziawg-go
//     генерирует их заново на каждое рукопожатие, а не один раз при выпуске
//     конфига панелью. Постоянны только структурные байты;
//   - поле длины — QUIC varint (RFC 9000 §16), обязано совпадать с числом
//     байт, идущих после него (Packet Number + Payload, RFC 9000 §17.2) —
//     это то, что легче всего сломать и что молча превращает пакет в мусор.
func generateQUICSignature(rnd io.Reader) (string, error) {
	// 8 байт — типичная длина DCID/SCID у существующих реализаций (ngtcp2,
	// QUICHE и др.); RFC 9000 верхнего предела не задаёт. Здесь важна не
	// длина сама по себе, а её постоянство между запусками панели —
	// содержимое случайно, длина — нет.
	const dcidLen = 8
	const scidLen = 8

	// Первый байт, раскладка RFC 9000 §17.2 (не "биты 7-6 — длинный
	// заголовок, бит 5 — fixed bit", как было в комментарии здесь раньше —
	// та версия задваивала бит 6 и сдвигала тип пакета на позицию левее):
	//   бит 7 — Header Form (1 = длинный заголовок);
	//   бит 6 — Fixed Bit (RFC 9000 §17.2 требует его установленным в 1);
	//   биты 5-4 — Long Packet Type (00 = Initial, RFC 9000 §17.2.2);
	//   биты 3-2 — Reserved;
	//   биты 1-0 — длина поля Packet Number минус 1.
	//
	// Верхний полубайт (0xc = 1100) фиксирован этой раскладкой: убрать его
	// значило бы перестать быть длинным заголовком Initial. Нижний полубайт
	// — НЕ константа, а случайное число 0x0-0xf, и это не украшение: у
	// НАСТОЯЩЕГО клиента первый байт защищён header protection (RFC 9001
	// §5.4.1, для длинных заголовков — `packet[0] ^= mask[0] & 0x0f`), маска
	// зависит от ключа и nonce конкретного соединения, и на проводе
	// наблюдатель видит равномерное распределение по всем 16 значениям
	// 0xc0..0xcf от пакета к пакету, а не одно и то же число. Прежняя
	// константа 0xc3 давала ИМЕННО такое одно число в каждом пакете от
	// каждого клиента этой панели — единственное сравнение по первому байту
	// ловило бы их все разом, то есть мы своими руками создавали ту же
	// сигнатуру, от которой профили должны защищать (см. HRange выше по
	// файлу — тот же принцип: одиночное значение есть отпечаток).
	nibble, err := randRange(rnd, 0, 15)
	if err != nil {
		return "", err
	}
	firstByte := byte(0xc0 | nibble)

	// extra — PADDING поверх обязательного минимума 1200 байт. Без этого
	// слагаемого длина датаграммы была бы одной и той же константой при
	// каждом вызове — числовой отпечаток вместо байтового.
	extra, err := randRange(rnd, 0, 200)
	if err != nil {
		return "", err
	}

	// overhead — все структурные байты ДО полезной нагрузки: первый байт (1)
	// + версия (4) + длина DCID и сам DCID (1+dcidLen) + длина SCID и сам
	// SCID (1+scidLen) + нулевая длина токена (1) + varint длины (2).
	const overhead = 1 + 4 + 1 + dcidLen + 1 + scidLen + 1 + 2
	ln := 1200 - overhead + extra // всё, что идёт ПОСЛЕ поля длины: Packet Number + Payload.

	// QUIC varint, 2-байтовая форма (верхние два бита поля значения — 01,
	// RFC 9000 §16): ln обязан помещаться в оставшиеся 14 бит. При
	// overhead=26 и extra ≤ 200 максимум ln — 1374, что далеко меньше
	// потолка 16383, но граница здесь явная, а не "не может случиться":
	// расширение диапазона extra выше сломало бы её молча без проверки.
	if ln > 0x3fff {
		return "", fmt.Errorf("varint длины Initial-пакета переполнен: %d > 0x3fff", ln)
	}
	lenVarint := []byte{0x40 | byte(ln>>8), byte(ln)}

	head1 := append([]byte{firstByte, 0x00, 0x00, 0x00, 0x01}, byte(dcidLen))
	head2 := []byte{byte(scidLen)}
	// 0x00 — нулевая длина токена: у клиентского Initial без Retry токена
	// нет (RFC 9000 §17.2.2).
	head3 := append([]byte{0x00}, lenVarint...)

	// ln здесь регулярно превышает maxRandomTagLen (минимум 1174 при
	// overhead=26), поэтому полезная нагрузка режется randTags на несколько
	// тегов `<r K≤1000>` — DCID/SCID тоже проходят через randTags ради
	// единообразия, хотя при 8 байтах в разбиении не нуждаются.
	return "<b 0x" + hex.EncodeToString(head1) + ">" + randTags(dcidLen) +
		"<b 0x" + hex.EncodeToString(head2) + ">" + randTags(scidLen) +
		"<b 0x" + hex.EncodeToString(head3) + ">" + randTags(ln), nil
}

// generateDNSSignature собирает DNS-ЗАПРОС (спека 2026-08-25, раздел 5.2).
//
// Прежняя версия этой функции (см. историю файла и git log) строила ОТВЕТ —
// унаследованная ошибка рецепта приложения AmneziaVPN: пакет I1 отправляет
// КЛИЕНТ СЕРВЕРУ, а в эту сторону летят запросы, не ответы. Непрошеный
// DNS-ответ — известная примета: часть промышленных межсетевых экранов
// сопоставляет идентификаторы транзакций (DNS Query Response Matching, у
// части вендоров — "DNS guard") и отбрасывает ответы без пары запроса.
//
// `<r 2>` идёт ПЕРВЫМ: первые два байта настоящего DNS-заголовка
// (RFC 1035 §4.1.1) — transaction ID, и это не то место, которым можно
// пожертвовать ради удобства — сдвинуть его на другую позицию значило бы
// построить пакет, невалидный как DNS вообще.
func generateDNSSignature(rnd io.Reader) (string, error) {
	di, err := randRange(rnd, 0, len(signatureDomains)-1)
	if err != nil {
		return "", err
	}

	var b []byte
	b = append(b, 0x01, 0x00) // флаги: стандартный запрос, recursion desired (RFC 1035 §4.1.1).
	b = append(b, 0x00, 0x01) // QDCOUNT = 1.
	b = append(b, 0x00, 0x00) // ANCOUNT = 0 — секции ответа у запроса нет вовсе.
	b = append(b, 0x00, 0x00) // NSCOUNT = 0.
	b = append(b, 0x00, 0x00) // ARCOUNT = 0.
	for _, label := range strings.Split(signatureDomains[di], ".") {
		b = append(b, byte(len(label)))
		b = append(b, label...)
	}
	b = append(b, 0x00)                   // терминатор QNAME.
	b = append(b, 0x00, 0x01, 0x00, 0x01) // QTYPE=A, QCLASS=IN.

	return randTags(2) + "<b 0x" + hex.EncodeToString(b) + ">", nil
}

// generateSTUNSignature собирает STUN Binding Request, RFC 5389 §6 (спека
// 2026-08-25, раздел 5.4, дополнено атрибутом SOFTWARE — см. ниже).
//
// Магическое печенье 0x2112a442 — фиксированная константа спецификации
// (RFC 5389 §6), менять нельзя: она добавлена в протокол ИМЕННО затем,
// чтобы отличать STUN от других протоколов на общем порту. Это намеренный
// опознавательный знак — имитация выходит убедительной, но всё, что несёт
// это печенье, однозначно объявляет себя STUN'ом, и подделывать его не
// нужно: оно само по себе часть маскировки под правильный протокол.
//
// Голый Binding Request без атрибутов — 20 байт: это короче порога в 32
// байта из официальной статьи Amnezia про мимикрию (сигнатура короче 32
// байт — примета сама по себе), и вдобавок нереалистично: настоящий STUN-
// запрос клиента WebRTC почти никогда не бывает голым заголовком. Поэтому
// добавлен атрибут SOFTWARE (тип 0x8022, RFC 5389 §15.10) со случайно
// выбранным именем библиотеки, дополненным нулями до кратности 4 байт
// (RFC 5389 §15: значения атрибутов выравниваются по границе 4 байт,
// паддинг в длину атрибута не входит). Итоговый пакет получается в районе
// 36-44 байт в зависимости от длины выбранного имени: выше порога в 32, и
// заметно короче общей рекомендации 100-500 байт для сигнатуры в целом —
// та рекомендация про сигнатуру целиком при нескольких профилях, а STUN по
// своей протокольной природе короткий: раздувать его до общей рекомендации
// значило бы имитировать протокол его же нетипичным трафиком.
//
// Поле длины сообщения (2 байта после типа) обязано равняться числу байт
// ПОСЛЕ 20-байтового заголовка — то есть всему атрибуту целиком, включая
// паддинг: RFC 5389 §6 определяет его именно так.
func generateSTUNSignature(rnd io.Reader) (string, error) {
	ni, err := randRange(rnd, 0, len(signatureSoftwareNames)-1)
	if err != nil {
		return "", err
	}
	value := []byte(signatureSoftwareNames[ni])
	pad := (4 - len(value)%4) % 4

	attr := make([]byte, 0, 4+len(value)+pad)
	attr = append(attr, 0x80, 0x22) // тип атрибута SOFTWARE, RFC 5389 §15.10.
	attr = append(attr, byte(len(value)>>8), byte(len(value)))
	attr = append(attr, value...)
	attr = append(attr, make([]byte, pad)...)

	head := make([]byte, 0, 8)
	head = append(head, 0x00, 0x01) // тип: Binding Request (RFC 5389 §6).
	head = append(head, byte(len(attr)>>8), byte(len(attr)))
	head = append(head, 0x21, 0x12, 0xa4, 0x42) // магическое печенье, менять нельзя (см. комментарий функции).

	return "<b 0x" + hex.EncodeToString(head) + ">" + randTags(12) + "<b 0x" + hex.EncodeToString(attr) + ">", nil
}
