// randRange возвращает целое из [lo, hi] включительно, читая источник.
// Источник параметром, а не crypto/rand.Reader внутри: генератор параметров
// обфускации обязан проверяться тестом на предсказуемом источнике, а
// math/rand здесь недопустим — параметры обфускации, выбранные
// предсказуемым генератором, обфускацией не являются.
func randRange(rnd io.Reader, lo, hi int) (int, error) {
	if lo > hi {
		return 0, fmt.Errorf("диапазон задом наперёд: %d..%d", lo, hi)
	}
	n, err := rand.Int(rnd, big.NewInt(int64(hi-lo+1)))
	if err != nil {
		return 0, fmt.Errorf("источник случайности: %w", err)
	}
	return lo + int(n.Int64()), nil
}

// Jitter — тройка клиентских параметров junk-пакетов. Сервер о ней не знает:
// в боевом awg3.conf этих полей нет вовсе (проверено 24.08.2026), они живут
// только в defaults.json и в оверрайдах пира. Поэтому генерация джиттера
// физически не может задеть живой туннель.
type Jitter struct {
	Jc   int `json:"jc"`
	Jmin int `json:"jmin"`
	Jmax int `json:"jmax"`
}

// GenerateJitter выдаёт тройку в диапазонах раздела 6.2 спеки 2026-08-24.
// Потолок Jmax — 1000 по построению, а не по явному зажиму: Jmin ∈
// [64,150], span ∈ [200,600], значит Jmax = Jmin+span ∈ [264,750] — заведомо
// меньше MTU боевых хостов (1280) при ЛЮБОЙ комбинации слагаемых. Зажим
// "if jmax > 1000 { jmax = 1000 }" здесь стоял раньше и был мёртвым кодом
// (750 < 1000 всегда): хуже, чем бесполезен, он маскировал бы будущую
// ошибку — если кто-то расширит span, например, до 900, Jmax молча упрётся
// в 1000 вместо честной 850, и никто не заметит расхождения с MTU. Сторож
// теперь — TestGenerateJitterДержитсяДиапазонов (internal/issuer/
// generate_test.go): она падает на первом же Jmax > 1000, то есть на самом
// расширении диапазонов, а не тихо проглатывает его зажимом (находка ревью
// задачи 8, Important #2).
// Границы Jc и Jmin сверены 25.08.2026 с генератором Any-Tech-ARCHITECT
// (MIT, github.com/Vadim-Khristenko/Any-Tech-ARCHITECT) — самой полной из
// известных реализаций правил AmneziaWG:
//
//	Jc: у них пресеты 0/3/5/7/10 с подписями «отключено / оптимально /
//	рекомендуемо / усиленный / максимальный» и умолчание 5. Каждый мусорный
//	пакет уходит ДО рукопожатия, то есть прямо добавляет задержку на каждом
//	перевыпуске ключа (у нас это раз в 115-140 с). Прежний потолок 10
//	доставал до их «максимального»; новый 7 — до «усиленного», а разброс
//	4..7 сохраняет переменность, ради которой диапазон и нужен.
//
//	Jmin: их самая низкая полоса размеров начинается с 64, ниже их генератор
//	не выдаёт никогда. Прежний пол 50 не нарушал ни одного правила
//	протокола, но давал значения, которых у чужих конфигов не бывает, — то
//	есть сам по себе слабый различитель.
func GenerateJitter(rnd io.Reader) (Jitter, error) {
	jc, err := randRange(rnd, 4, 7)
	if err != nil {
		return Jitter{}, err
	}
	jmin, err := randRange(rnd, 64, 150)
	if err != nil {
		return Jitter{}, err
	}
	span, err := randRange(rnd, 200, 600)
	if err != nil {
		return Jitter{}, err
	}
	jmax := jmin + span
	return Jitter{Jc: jc, Jmin: jmin, Jmax: jmax}, nil
}

// HRange — полоса значений заголовка. AmneziaWG допускает и одиночное
// число, и диапазон «x-y», но одиночное значение означает, что КАЖДЫЙ пакет
// данного типа несёт одну и ту же четырёхбайтовую константу — идеальный
// отпечаток сервера, который DPI ловит одним сравнением, увидев его
// однажды. Полоса заставляет значение меняться от пакета к пакету.
type HRange struct {
	Lo uint32 `json:"lo"`
	Hi uint32 `json:"hi"`
}

func (r HRange) String() string {
	return strconv.FormatUint(uint64(r.Lo), 10) + "-" + strconv.FormatUint(uint64(r.Hi), 10)
}

// hRanges строит четыре НЕПЕРЕСЕКАЮЩИЕСЯ полосы. Ширины у H1..H3 и у H4
// РАЗНЫЕ, и это не вкусовщина: при RandomTrailers = on приёмник примеряет
// КАЖДЫЙ транспортный пакет к полосам H1..H3 и молча теряет долю
// (W1+W2+W3)/2³² исправных пакетов (механизм разобран в
// TestПолосыH1H3УзкиеИначеТеряютсяПакеты; на боевом эталоне это стоило
// 16.9 % потерь в каждую сторону). Полоса H4 в этой цене не участвует —
// ветка transport в DeterminePacketTypeAndPadding проверяется последней и
// ни с чем не конкурирует, — поэтому широкой остаётся именно она, там, где
// 99.9 % пакетов и вся видимая наблюдателю энтропия.
//
// Пространство 5…INT32_MAX
// делится на четыре равные четверти, и полоса i выбирается ВНУТРИ своей
// четверти — поэтому пересечься полосы не могут по построению, а не потому
// что мы это потом проверили. Пересечение сервер отвергает на старте, и
// генератор, способный его выдать, был бы генератором нерабочих конфигов.
func hRanges(rnd io.Reader) ([4]HRange, error) {
	const minH, maxH = 5, 2147483647
	const quarter = (maxH - minH) / 4
	// H1..H3 — рукопожатия. Полоса нужна лишь затем, чтобы значение не было
	// константой, а платится за неё молча потерянными транспортными пакетами,
	// поэтому она узкая. Ориентир — канонический образец протокола
	// (H1 = 666067622-666092814) шириной 25 192.
	const handshakeWidthLo, handshakeWidthHi = 10_000, 30_000
	// H4 — транспорт. Его ширина ничего не стоит.
	const transportWidthLo, transportWidthHi = 50_000_000, 400_000_000
	var out [4]HRange
	for i := 0; i < 4; i++ {
		lo := minH + i*quarter
		hi := lo + quarter - 1
		widthLo, widthHi := handshakeWidthLo, handshakeWidthHi
		if i == 3 {
			widthLo, widthHi = transportWidthLo, transportWidthHi
		}
		width, err := randRange(rnd, widthLo, widthHi)
		if err != nil {
			return out, err
		}
		// Зажим "if width > hi-lo { width = hi - lo }" стоял здесь и был
		// мёртвым кодом: width ≤ 400 000 000 по построению randRange выше (а
		// у H1..H3 теперь и вовсе ≤ 30 000), а
		// hi-lo = quarter-1 = 536 870 909 при текущих minH/maxH — четверть
		// пространства ЗАВЕДОМО шире максимально возможной ширины полосы, и
		// сработать зажим не мог никогда (находка финального ревью #6, как
		// мёртвый Jmax-зажим в GenerateJitter выше по файлу). Он вводил в
		// заблуждение читателя, будто полоса способна оказаться Уже
		// сгенерированного width — такого не бывает.
		start, err := randRange(rnd, lo, hi-width)
		if err != nil {
			return out, err
		}
		out[i] = HRange{Lo: uint32(start), Hi: uint32(start + width)}
	}
	return out, nil
}

// InterfaceParams — комплект параметров для НОВОГО интерфейса.
//
// Этот тип не умеет применяться. У него нет и не будет метода, пишущего в
// серверный конфиг: правило 2 репозитория запрещает существование кода,
// способного изменить [Interface], и генерация — не исключение из него.
// Комплект печатается текстом, оператор накатывает его руками при подъёме
// нового туннеля.
type InterfaceParams struct {
	S1 int `json:"s1"`
	S2 int `json:"s2"`
	S3 int `json:"s3"`
	S4 int `json:"s4"`

	H1 HRange `json:"h1"`
	H2 HRange `json:"h2"`
	H3 HRange `json:"h3"`
	H4 HRange `json:"h4"`

	HeaderProtectionKey    string `json:"header_protection_key"`
	ContentPaddingAddition string `json:"content_padding_addition"`
	Jitter                 Jitter `json:"jitter"`

	// I1 — сигнатурный пакет профиля мимикрии, переданного в
	// GenerateInterfaceParams (см. GenerateSignatureFor). Клиентское поле:
	// оно ОДНОСТОРОННЕЕ (README amneziawg-go — "no need to specify it on
	// both sides"), сервер о нём не знает, и в ServerBlock оно поэтому не
	// печатается — печатать было бы некуда, в [Interface] такого поля нет.
	I1 string `json:"i1"`

	// ListenPort — канонический порт того же профиля мимикрии, что и I1
	// выше (раздел 5.7 спеки 2026-08-25). GenerateInterfaceParams заполняет
	// оба поля из ОДНОГО параметра profile одним вызовом PortForProfile —
	// они не могут разойтись между собой так, как расходились до находки
	// финального ревью ветки mimicry-profiles, когда I1 генерировался внутри
	// GenerateInterfaceParams одним (фиксированным) профилем, а ListenPort
	// подставлялся вызывающим кодом снаружи другим, явно выбранным. В
	// отличие от I1 (клиентское, одностороннее поле) ListenPort — часть
	// серверного [Interface] и печатается ServerBlock() первой строкой:
	// оператор, поднимающий новый туннель, получает согласованную пару
	// «порт + параметры обфускации» сразу и не должен помнить таблицу
	// profilePort.
	ListenPort int `json:"listen_port"`
}

// Длины сообщений WireGuard ДО паддинга. Паддинг S1..S3 ставится ровно затем,
// чтобы три типа сообщений различались ПО ДЛИНЕ: наблюдателю, считающему
// длины, иначе не нужно ничего расшифровывать, чтобы отличить рукопожатие от
// cookie reply.
const (
	msgInitiationSize = 148
	msgResponseSize   = 92
	msgCookieSize     = 64
)

// sizesCollide сообщает, дают ли S1..S3 два одинаковых по длине типа
// сообщения.
//
// Правило выражено через САМИ ДЛИНЫ, а не через три вынесенных смещения
// (S2 != S1+56, S3 != S1+84, S3 != S2+28), и это намеренно: смещение можно
// списать неверно и годами не замечать. Any-Tech-ARCHITECT (MIT, Vadim
// Khristenko) поймал у себя ровно это — два смещения из трёх были записаны
// как размеры сообщений вместо разностей, инструмент предупреждал о паре,
// которая совпасть не может, и молчал о реальной (их issue #7). Разность
// длин, посчитанную на месте, списать нельзя.
func sizesCollide(s1, s2, s3 int) bool {
	initiation, response, cookie := msgInitiationSize+s1, msgResponseSize+s2, msgCookieSize+s3
	return initiation == response || initiation == cookie || response == cookie
}

// GenerateInterfaceParams — диапазоны и правила раздела 6 спеки 2026-08-24,
// плюс I1 и ListenPort выбранного профиля мимикрии (раздел 5.7 спеки
// 2026-08-25).
//
// profile — обязательный параметр, а не внутреннее умолчание функции.
// Раньше (до находки финального ревью ветки mimicry-profiles) функция сама
// решала за вызывающего — безусловно собирала DNS-пакет через прежнюю
// GenerateSignaturePacket, — а единственный вызывающий,
// handleGenerateInterfaceParams, всё равно перегенерировал I1 нужным
// профилем поверх и переписывал ListenPort отдельной строкой: первая
// генерация I1 уходила в мусор на каждом запросе, а метод, дающий кит через
// ServerBlock() без этой перезаписи (как делает
// TestServerBlockНесётВсеОбязательныеПоля), тихо получал бы ListenPort = 0
// — правдоподобную на вид, но нерабочую первую строку [Interface]. Профиль
// параметром убирает оба риска разом: I1 и ListenPort берутся из одного
// источника одним вызовом ниже.
func GenerateInterfaceParams(rnd io.Reader, profile MimicryProfile) (InterfaceParams, error) {
	var p InterfaceParams
	var err error
	// S1..S4 РАВНЫ — замер 05.09.2026 на боевом awgref и разбор
	// device/receive.go (DeterminePacketTypeAndPadding): при RandomTrailers = on
	// каждая ветка классификатора читает 4 байта заголовка по СВОЕМУ смещению
	// S, и при S1 ≠ S4 транспортный пакет длиннее S1+148 примеряется к H1 по
	// случайным байтам — с вероятностью ширина(H1)/2³² он молча уходит в очередь
	// рукопожатий и умирает на MAC1 без счётчика (amneziawg-go #186, kmod #226).
	// При равных S ветка читает НАСТОЯЩЕЕ поле типа транспортного пакета —
	// значение из H4, а H1..H3 с ним не пересекаются, — и кража становится
	// невозможной, а не «маловероятной». То же рекомендует docs.amnezia.org
	// («при RandomTrailers задавайте одинаковые S1..S4»), и вендор в
	// amnezia-client 5.0.2.1 снял своё прежнее требование уникальности S.
	// Правило неколлизий длин (sizesCollide) при равных S выполняется само:
	// 148+S ≠ 92+S ≠ 64+S. Коридор 12..32: ≥ 12 — нонс ChaCha20 защиты
	// заголовков, ≤ 32 — потолок S4, который падит КАЖДЫЙ транспортный пакет.
	sz, err := randRange(rnd, 12, 32)
	if err != nil {
		return InterfaceParams{}, err
	}
	p.S1, p.S2, p.S3, p.S4 = sz, sz, sz, sz
	if sizesCollide(p.S1, p.S2, p.S3) {
		return InterfaceParams{}, fmt.Errorf("внутренняя ошибка: равные S дали совпадение длин сообщений")
	}

	// H1..H4: непересекающиеся полосы, не меньше 5 — значения 1..4 заняты
	// стандартными типами пакетов WireGuard. Потолок INT32_MAX, а не
	// UINT32_MAX: клиенты со знаковым разбором на большем ломаются.
	// Непересечение обеспечивает сама hRanges построением по четвертям
	// пространства значений (см. её комментарий) — дедупликация здесь не
	// нужна, а вместе с ней не нужен и ограничитель попыток: полосы физически
	// не могут совпасть, сколько бы раз функция ни вызывалась.
	hs, err := hRanges(rnd)
	if err != nil {
		return InterfaceParams{}, err
	}
	p.H1, p.H2, p.H3, p.H4 = hs[0], hs[1], hs[2], hs[3]

	// 32 байта в base64 — проверено по живому /etc/amnezia/amneziawg/awg3.conf
	// 24.08.2026. Стороннее README обещает hex; при расхождении документации
	// с живым конфигом источником правды считается живой конфиг.
	key := make([]byte, 32)
	if _, err := io.ReadFull(rnd, key); err != nil {
		return InterfaceParams{}, fmt.Errorf("источник случайности: %w", err)
	}
	p.HeaderProtectionKey = base64.StdEncoding.EncodeToString(key)

	cpa, err := randRange(rnd, 64, 128)
	if err != nil {
		return InterfaceParams{}, err
	}
	p.ContentPaddingAddition = fmt.Sprintf("0-%d", cpa)

	if p.Jitter, err = GenerateJitter(rnd); err != nil {
		return InterfaceParams{}, err
	}

	if p.I1, err = GenerateSignatureFor(rnd, profile); err != nil {
		return InterfaceParams{}, err
	}
	// profile уже прошёл GenerateSignatureFor выше без ошибки, то есть это
	// один из трёх ключей profilePort — PortForProfile для него гарантированно
	// найдёт порт, второй результат здесь не признак ошибки, а формальность.
	p.ListenPort, _ = PortForProfile(profile)
	return p, nil
}

// ServerBlock — текст полей для вставки в [Interface] нового сервера.
// Порядок фиксирован списком, а не обходом карты: один и тот же комплект
// обязан давать один и тот же текст. ListenPort печатается ПЕРВОЙ строкой
// (раздел 5.7 спеки 2026-08-25) — оператор, поднимающий новый туннель,
// первым делом должен открыть порт и указать его в [Interface], и порт
// профиля мимикрии здесь единственно верный: он обязан совпадать с тем, по
// которому ProfileForPort вернёт тот же профиль, иначе сигнатурный пакет I1
// ниже придёт на порт, который его не объясняет (раздел 1 спеки).
func (p InterfaceParams) ServerBlock() string {
	return fmt.Sprintf(
		"ListenPort = %d\n"+
			"S1 = %d\nS2 = %d\nS3 = %d\nS4 = %d\n"+
			"H1 = %s\nH2 = %s\nH3 = %s\nH4 = %s\n"+
			"HeaderProtectionKey = %s\nContentPaddingAddition = %s\n"+
			// Флаги 3.1 — часть комплекта, а не опция: без них оператор получал
			// бы «эталон» уровня 3.0 и включал бы их руками. RandomTrailers
			// ДВУСТОРОННИЙ (приёмник разбирает хвост по своему флагу,
			// receive.go), DisableCookies односторонний — клиенту переносится
			// через ExtractObfuscation безвредно, но совпадать не обязан.
			"RandomTrailers = on\nDisableCookies = on\n",
		p.ListenPort,
		p.S1, p.S2, p.S3, p.S4, p.H1.String(), p.H2.String(), p.H3.String(), p.H4.String(),
		p.HeaderProtectionKey, p.ContentPaddingAddition)
}

// MimicryProfile — какой чужой протокол имитирует сигнатурный пакет I1.
// Три константы ниже — единственные допустимые значения; строка выбрана
// типом (а не iota), потому что профиль путешествует как есть в HTTP JSON
// (тело запроса generate/signature, query interface-params) и в логах —
// незачем городить отдельный маппинг строка↔число для сериализации того,
// что и так строка по природе.
type MimicryProfile string

const (
	MimicryQUIC MimicryProfile = "quic"
	MimicryDNS  MimicryProfile = "dns"
	MimicrySTUN MimicryProfile = "stun"
)

// profilePort — ЕДИНСТВЕННАЯ таблица соответствия «профиль → канонический
// порт» (раздел 5.1 спеки 2026-08-25). ProfileForPort и PortForProfile ниже
// читают только её: обратного поиска второй картой здесь нет и не должно
// появиться — при добавлении профиля достаточно дописать одну строку сюда,
// а не синхронизировать две структуры вручную, которые иначе разойдутся при
// первой же правке и разведут подсказку порта в комплекте параметров с
// автоматическим выбором профиля по порту интерфейса.
var profilePort = map[MimicryProfile]int{
	MimicryQUIC: 443,
	MimicryDNS:  53,
	MimicrySTUN: 3478,
}

// ProfileForPort ищет профиль мимикрии, чей канонический порт совпадает с
// портом интерфейса. Второй результат — не признак ошибки: у оператора
// вполне может быть туннель на нестандартном порту, и это лишь означает
// «под этот порт профиля нет» — вызывающий код сам решает, что делать
// (раздел 5.5 спеки: не сеять I1 вовсе, а не подставлять профиль по
// умолчанию).
func ProfileForPort(port int) (MimicryProfile, bool) {
	for p, pt := range profilePort {
		if pt == port {
			return p, true
		}
	}
	return "", false
}

// PortForProfile — обратный поиск по той же единственной таблице
// profilePort: подсказка порта в комплекте параметров нового интерфейса
// обязана совпадать с тем портом, по которому ProfileForPort вернёт этот же
// профиль — иначе панель советовала бы один порт, а выбирала бы профиль по
// другому.
func PortForProfile(p MimicryProfile) (int, bool) {
	port, ok := profilePort[p]
	return port, ok
}

// ValidProfile разбирает строку из HTTP-запроса (тело generate/signature,
// query-параметр interface-params) в MimicryProfile. Строгий разбор: только
// три точных значения ключей profilePort, включая регистр — "QUIC" или
// хвостовой пробел не распознаются, потому что тихая нормализация входа
// маскировала бы опечатку в запросе клиента панели. Пустая строка тоже "не
// распознано": различение «профиль не выбран явно» от «профиль указан
// неверно» — забота вызывающего кода (задача 2+), а не этой функции.
func ValidProfile(s string) (MimicryProfile, bool) {
	p := MimicryProfile(s)
	if _, ok := profilePort[p]; !ok {
		return "", false
	}
	return p, true
}

// mimicryProfileOrder — фиксированный порядок вывода профилей в подсказках
// и текстах ошибок (тот же порядок, в котором они перечислены в разделе 5.1
// спеки 2026-08-25). Обход profilePort напрямую дал бы порядок, случайный
// от вызова к вызову (map), — а текст, каждый раз перечисляющий варианты
// иначе, оператору неприятно читать и невозможно сверить между двумя
// обращениями к одному и тому же маршруту.
var mimicryProfileOrder = []MimicryProfile{MimicryQUIC, MimicryDNS, MimicrySTUN}

// ProfilePortHints форматирует ЕДИНСТВЕННУЮ таблицу profilePort в подсказку
// вида "quic: 443, dns: 53, stun: 3478" — используется маршрутом
// generate/signature (раздел 5.5 спеки 2026-08-25), когда порт интерфейса не
// соответствует ни одному профилю, а профиль не указан явно: оператору
// нужно увидеть варианты, чтобы выбрать один явно, а не запоминать таблицу
// или лезть в спеку. Читает profilePort через PortForProfile, а не заводит
// отдельный список портов — иначе при добавлении профиля эта подсказка
// расходилась бы с таблицей соответствия так же, как предупреждала бы себя
// не делать документация раздела 5.1.
func ProfilePortHints() string {
	parts := make([]string, 0, len(mimicryProfileOrder))
	for _, p := range mimicryProfileOrder {
		port, _ := PortForProfile(p) // p всегда из profilePort — mimicryProfileOrder её не расширяет.
		parts = append(parts, fmt.Sprintf("%s: %d", p, port))
	}
	return strings.Join(parts, ", ")
}

// literalTagRe находит ПЕРВЫЙ тег `<b 0x...>` в CPS-строке I1: ровно так эти
// теги печатают generateQUICSignature/generateDNSSignature/
// generateSTUNSignature (см. их код выше) — литерал байт, hex без учёта
// регистра, между `<b 0x` и `>`.
var literalTagRe = regexp.MustCompile(`<b 0x([0-9a-fA-F]+)>`)

// firstLiteralBytes достаёт байты ПЕРВОГО литерального тега `<b 0x...>` из
// CPS-строки I1. Случайные теги `<r N>` перед ним (как `<r 2>` — transaction
// ID в начале DNS-профиля) структурных признаков не несут и пропускаются —
// опознавательные байты каждого из трёх профилей (см. DetectProfile) лежат
// именно в первом литерале, а не в случайной части.
func firstLiteralBytes(i1 string) ([]byte, bool) {
	m := literalTagRe.FindStringSubmatch(i1)
	if m == nil {
		return nil, false
	}
	b, err := hex.DecodeString(m[1])
	if err != nil {
		return nil, false
	}
	return b, true
}

// DetectProfile опознаёт профиль мимикрии лежащего I1 по его СТРУКТУРНЫМ
// БАЙТАМ (раздел 5.6 спеки 2026-08-25), а не по отдельному полю рядом с
// I1 в defaults.json: такого поля не существует, а если бы оно и было,
// оператор мог заполнить defaults.json руками — метка разошлась бы с
// фактическим содержимым пакета, и предупреждение о несоответствии порта
// опиралось бы на неправду.
//
// Признаки — первые байты первого литерала `<b 0x...>` (firstLiteralBytes),
// то есть ровно то место, где каждый из трёх сборщиков (generateQUICSignature/
// generateDNSSignature/generateSTUNSignature) кладёт свою структурную часть
// раньше любых случайных байт:
//   - QUIC: старший полубайт первого байта равен 0xc — биты Header Form,
//     Fixed Bit и старший бит Long Packet Type (RFC 9000 §17.2) фиксированы,
//     младший полубайт варьируется header protection'ом (см. комментарий
//     generateQUICSignature) и потому в проверке не участвует — и следом
//     идёт версия 0x00000001;
//   - DNS-запрос: флаги 0x0100 (стандартный запрос, RFC 1035 §4.1.1) —
//     первые два байта литерала, потому что transaction ID (`<r 2>`) у DNS-
//     профиля идёт ДО литерала, а не внутри него;
//   - STUN: магическое печенье 0x2112a442 (RFC 5389 §6) на смещении 4
//     внутри 8-байтового заголовка Binding Request (тип 2 байта + длина
//     сообщения 2 байта + печенье 4 байта).
//
// Признаки взаимно исключают друг друга по построению генераторов (первый
// байт QUIC всегда 0xc0..0xcf и не проходит DNS-проверку — старший полубайт
// 0xc, а не 0x0; первые байты STUN 0x00 0x01 не равны 0x01 0x00 DNS; и
// т.д.), поэтому порядок проверок ниже не влияет на результат для НАСТОЯЩИХ
// сгенерированных пакетов — он важен только для того, чтобы не выйти за
// границы слайса на короткой входной строке.
//
// Строка, не подошедшая ни под один шаблон, даёт false — это НЕ ошибка
// (явно оговорено разделом 5.6): пустой I1, ручной мусор в defaults.json,
// формат из будущей версии панели — всё это законные причины не опознать
// профиль, отличные от "I1 точно указывает на несогласованный порт".
func DetectProfile(i1 string) (MimicryProfile, bool) {
	b, ok := firstLiteralBytes(i1)
	if !ok {
		return "", false
	}
	switch {
	case len(b) >= 8 && b[4] == 0x21 && b[5] == 0x12 && b[6] == 0xa4 && b[7] == 0x42:
		return MimicrySTUN, true
	case len(b) >= 5 && b[0]&0xf0 == 0xc0 && b[1] == 0x00 && b[2] == 0x00 && b[3] == 0x00 && b[4] == 0x01:
		return MimicryQUIC, true
	case len(b) >= 2 && b[0] == 0x01 && b[1] == 0x00:
		return MimicryDNS, true
	}
	return "", false
}

