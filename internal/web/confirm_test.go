package web_test

import (
	"net/http"
	"strings"
	"testing"
)

// TestConfirmByNameNeverFailsSilently — необратимые действия консоли
// (удаление пира, ротация ключей) подтверждаются вводом имени, и промах при
// наборе обязан быть СКАЗАН человеку.
//
// Тест написан по факту с боевого хоста, а не из общих соображений. Прежняя
// редакция обоих подтверждений выглядела как
//
//	if (typed !== p.name) return;
//
// то есть при малейшем расхождении молча ничего не делала: ни запроса на
// сервер, ни плашки, ни строки в журнале. На awg3 пять пиров из шести
// назывались «peer-<12 hex>» (см. wgconf.PeerName и историю вокруг неё),
// точно ввести такое имя практически невозможно, и оператор наблюдал ровно
// то, что должен был наблюдать: кнопка «Удалить» не работает. Диагностика
// заняла отдельную сессию, потому что серверный журнал был чист —
// удаление до сервера не доходило.
//
// Проверяется не текст сообщения, а инвариант: подтверждение существует
// единой функцией, каждый выход из неё по несовпадению показывает плашку, и
// прежнего молчаливого выхода в разметке не осталось.
func TestConfirmByNameNeverFailsSilently(t *testing.T) {
	body := doAuthed(t, newTestServerWithMutator(t, &fakeMutator{}), http.MethodGet, "/", nil).Body.String()

	for _, silent := range []string{
		"if (typed !== p.name) return;",
		"if (typed !== name) return;",
	} {
		if strings.Contains(body, silent) {
			t.Errorf("в разметке остался молчаливый выход по несовпадению имени: %s", silent)
		}
	}

	if n := strings.Count(body, "function confirmByName("); n != 1 {
		t.Fatalf("объявлений confirmByName = %d, ожидалось ровно одно: "+
			"подтверждение обязано быть одним на все необратимые действия", n)
	}
	if n := strings.Count(body, "confirmByName("); n < 3 {
		t.Errorf("вызовов confirmByName = %d (вместе с объявлением), "+
			"ожидались минимум два — удаление и ротация", n)
	}
	if !strings.Contains(body, "Имя не совпало") {
		t.Error("нет сообщения о несовпадении имени — промах при наборе снова молчалив")
	}
}
